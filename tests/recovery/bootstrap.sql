create table public.leads(
 lead_id bigint generated by default as identity primary key,
 first_name text, last_name text, notes text, lead_email text,
 created_at timestamptz default now(), status boolean default true
);
create table public.tasks(
 task_id bigint generated by default as identity primary key,
 lead_id bigint references public.leads, title text, task_date timestamptz, completed boolean default false
);
create table public.notifications(
 notification_id bigint generated by default as identity primary key,
 lead_id bigint references public.leads, title text, date timestamptz
);
create table public.vehicles(
 vehicle_id bigint generated by default as identity primary key,
 make text, model text, year integer
);
create table public.lead_vehicle_interests(
 lead_id bigint references public.leads, vehicle_id bigint references public.vehicles,
 primary key(lead_id,vehicle_id)
);
create table public.lead_trade_in_vehicles(
 lead_id bigint references public.leads, vehicle_id bigint references public.vehicles,
 primary key(lead_id,vehicle_id)
);
create table public.imported_cars(id bigint generated by default as identity primary key, make text);
grant usage, select on all sequences in schema public to authenticated;
-- Deliberately permissive legacy policies and grants must not survive migrations.
grant all on all tables in schema public to anon, authenticated;
alter table public.leads enable row level security;
create policy legacy_allow_all on public.leads for all using(true) with check(true);
