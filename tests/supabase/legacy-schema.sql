begin;
create table public.leads (
  lead_id bigint generated by default as identity primary key,
  first_name text, last_name text, phone text, lead_email text, lead_division text,
  lead_address text, lead_city text, lead_province text, lead_country text,
  lead_postal_code text, budget numeric, stage text, follow_up_date timestamptz,
  score integer, notes text, created_at timestamptz default now(),
  last_interaction_date timestamptz, last_interaction_by text, status boolean default true
);
create table public.tasks (
  task_id bigint generated by default as identity primary key,
  lead_id bigint references public.leads, title text, task_date timestamp,
  completed boolean default false
);
create table public.notifications (
  notification_id bigint generated by default as identity primary key,
  lead_id bigint references public.leads, title text, date timestamptz
);
create table public.vehicles (
  vehicle_id bigint generated by default as identity primary key,
  make text, model text, year integer, trim text, price numeric, color text,
  in_stock boolean, vin text, transmission text
);
create table public.lead_vehicle_interests (
  lead_id bigint primary key references public.leads,
  vehicle_id bigint not null references public.vehicles,
  trim_override text, updated_at timestamptz default now()
);
create table public.lead_trade_in_vehicles (
  lead_id bigint primary key references public.leads,
  vehicle_id bigint not null references public.vehicles,
  updated_at timestamptz default now()
);
create table public.imported_cars (
  id bigint generated by default as identity primary key, make text
);

